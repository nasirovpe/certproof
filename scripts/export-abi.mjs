import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const compiledArtifactPath = path.join(
  rootDir,
  'contracts',
  'out',
  'CertProofRegistry.sol',
  'CertProofRegistry.json'
);

if (!fs.existsSync(compiledArtifactPath)) {
  console.error(`Compiled artifact not found at ${compiledArtifactPath}. Run forge build first.`);
  process.exit(1);
}

const artifact = JSON.parse(fs.readFileSync(compiledArtifactPath, 'utf8'));
const abi = artifact.abi;

const targetAbiDir = path.join(rootDir, 'contracts', 'abi');
fs.mkdirSync(targetAbiDir, { recursive: true });

const jsonTarget = path.join(targetAbiDir, 'CertProofRegistry.json');
fs.writeFileSync(jsonTarget, JSON.stringify(abi, null, 2));

const tsTarget = path.join(targetAbiDir, 'CertProofRegistry.ts');
const tsContent = `// Autogenerated by scripts/export-abi.mjs — DO NOT EDIT DIRECTLY
export const CertProofRegistryABI = ${JSON.stringify(abi, null, 2)} as const;
`;
fs.writeFileSync(tsTarget, tsContent);

// Also sync to frontend if frontend directory exists
const frontendAbiDir = path.join(rootDir, 'frontend', 'src', 'lib', 'abi');
if (fs.existsSync(frontendAbiDir)) {
  fs.writeFileSync(path.join(frontendAbiDir, 'CertProofRegistry.ts'), tsContent);
}

console.log('ABI exported successfully:');
console.log(`- JSON: ${jsonTarget} (${abi.length} entries)`);
console.log(`- TypeScript: ${tsTarget}`);
if (fs.existsSync(frontendAbiDir)) {
  console.log(`- Frontend TypeScript: ${path.join(frontendAbiDir, 'CertProofRegistry.ts')}`);
}

// Verify essential items are present
const functions = abi.filter(x => x.type === 'function').map(x => x.name);
const events = abi.filter(x => x.type === 'event').map(x => x.name);
const errors = abi.filter(x => x.type === 'error').map(x => x.name);

console.log(`Functions (${functions.length}): ${functions.join(', ')}`);
console.log(`Events (${events.length}): ${events.join(', ')}`);
console.log(`Errors (${errors.length}): ${errors.join(', ')}`);

const requiredFunctions = [
  'setIssuerAuthorization',
  'registerCertificate',
  'revokeCertificate',
  'getCertificate',
  'certificateExists',
  'isIssuerAuthorized',
  'getIssuerCertificates',
  'getIssuerCertificateCount',
  'renounceOwnership',
];

for (const fn of requiredFunctions) {
  if (!functions.includes(fn)) {
    throw new Error(`Missing expected function in exported ABI: ${fn}`);
  }
}
